function toClodexModel(resolved) {
  const id = resolved.id;
  const transport = TRANSPORTS[id];
  const anthropic = transport === 'anthropic-messages';
  const cache = resolved.cost?.cache ?? {};
  const cost = {
    input: resolved.cost?.input ?? 0,
    output: resolved.cost?.output ?? 0,
    ...(cache.read ? { cache_read: cache.read } : {}),
    ...(cache.write ? { cache_write: cache.write } : {}),
  };
  // Defaults every anthropic-format entry carries, overridable per model.
  //
  // supportsCountTokens: OpenCode Zen documents /v1/responses,
  // /v1/chat/completions and /v1/messages, and no token-counting endpoint, so
  // the proxy answers count_tokens from its local estimate instead of
  // forwarding to a path that 404s into the client's token accounting.
  //
  // supportsReasoningEffort: structural, not a vendor claim. Effort reaches an
  // upstream through `effortProviderOptions` and the `thinkingFormat`
  // transform, both of which act on an OpenAiCompatibleRequestBody. A
  // passthrough Messages body is forwarded untouched, so there is no way to
  // send a graded effort on this route however the vendor spells it — these
  // models still reason, via whatever `thinking` the client itself sends.
  // Advertising a control clodex cannot operate is what this prevents.
  const compatibility = anthropic
    ? { supportsCountTokens: false, supportsReasoningEffort: false, ...(PATCHES[id] ?? {}) }
    : PATCHES[id];
  const modalities = ['text', 'image'].filter(modality => resolved.capabilities?.input?.[modality] === true);
  // Where the upstream streams its reasoning text. Previously left unset, so
  // every consumer fell back to whatever the bundled models.dev cache happened
  // to know — which is nothing at all for the newer ids. The resolver states it
  // per model, so state it here and stop depending on that fallback.
  const interleaved = resolved.capabilities?.interleaved;

  return {
    id,
    name: resolved.name,
    contextWindow: resolved.limit?.context,
    cost,
    modelFormat: anthropic ? 'anthropic' : 'openai',
    npm: anthropic ? '@ai-sdk/anthropic' : '@ai-sdk/openai-compatible',
    apiUrl: anthropic ? ANTHROPIC_BASE_URL : COMPLETIONS_BASE_URL,
    reasoning: resolved.capabilities?.reasoning === true,
    ...(interleaved ? { interleavedReasoningField: interleaved.field } : {}),
    modalities,
    ...(compatibility ? { compatibility } : {}),
    upstreamModelId: id,
    // The resolver's own grouping ("kimi-k2", "qwen3.7-max") rather than the
    // first id segment. `deriveBrand` prefix-matches, so every brand is
    // unchanged; what improves is that models sharing a deployment now share a
    // family name instead of collapsing a whole vendor into one bucket.
    family: resolved.family,
  };
}

/**
 * Project the validated resolver rows onto the clodex catalog shape.
 *
 * Membership is the intersection of the snapshot and TRANSPORTS, never the
 * snapshot alone: an id clodex has not routed on the wire is reported as
 * unmapped rather than shipped.
 */
export function convertResolvedModels(models) {
  assertResolvedModels(models);
  const overrides = crossCheckTransports(models);
  const temperatureNotes = crossCheckTemperatureSupport(models);
  const supported = [];
  const unmapped = [];
  for (const resolved of [...models].sort((a, b) => compareCodeUnits(a.id, b.id))) {
    if (!TRANSPORTS[resolved.id]) {
      unmapped.push(resolved.id);
      continue;
    }
    supported.push(toClodexModel(resolved));
  }
  if (supported.length === 0) throw new Error('resolver snapshot produced no supported models');
  const effortProfiles = buildEffortProfiles(models, supported);
  return { supported, unmapped, overrides, temperatureNotes, effortProfiles };
}

function raiseEffortProfileErrors(errors) {
  if (errors.length > 0) {
    throw new Error(`OpenCode Go effort profiles failed validation:\n  ${errors.join('\n  ')}`);
  }
}

/**
 * Fail closed unless every reviewed effort map is a fixed point on its own output.
 *
 * Two request paths reach the same upstream. The SDK path maps a global level to
 * its native value BEFORE the AI SDK serializes the body, and
 * `transformOpenAiCompatibleRequestBody` then runs over that serialized body —
 * so a map that also has an entry for one of its own outputs would translate the
 * same request twice and send something neither path intended. The direct
 * chat-completions forward has the mirror problem: a client may already spell
 * the native value, and the two paths can only agree byte for byte if mapping an
 * already-native value is a no-op.
 *
 * The injectivity half exists for the same reason from the other direction: if
 * two global levels sent the same native value, an incoming native value could
 * not be attributed back to one level, and the direct path would have to guess.
 */
export function assertEffortMapsIdempotent(patches = PATCHES) {
  const errors = [];
  for (const [id, patch] of Object.entries(patches)) {
    const map = patch?.reasoningEffortMap;
    if (map === undefined) continue;
    if (!isPlainObject(map)) {
      errors.push(`${id}: reasoningEffortMap must be an object`);
      continue;
    }
    const levelByNative = new Map();
    for (const [level, native] of Object.entries(map)) {
      if (!CANONICAL_EFFORT_LEVELS.includes(level)) {
        errors.push(`${id}: reasoningEffortMap key ${JSON.stringify(level)} is not a global effort level`);
        continue;
      }
      if (native === null) continue;
      if (typeof native !== 'string' || native.trim() === '') {
        errors.push(`${id}: reasoningEffortMap.${level} must be null or a non-empty string`);
        continue;
      }
      const claimed = levelByNative.get(native);
      if (claimed !== undefined) {
        errors.push(
          `${id}: reasoningEffortMap sends ${JSON.stringify(native)} for both ${claimed} and ${level}, `
          + 'so an already-native request value cannot be attributed to one level',
        );
        continue;
      }
      levelByNative.set(native, level);
    }
    for (const native of levelByNative.keys()) {
      if (!Object.hasOwn(map, native)) continue;
      if (map[native] !== native) {
        errors.push(
          `${id}: reasoningEffortMap is not idempotent — ${JSON.stringify(native)} is one of its own outputs `
          + `but maps to ${JSON.stringify(map[native])}`,
        );
      }
    }
  }
  raiseEffortProfileErrors(errors);
  return true;
}

/** The reasoning representation one resolver variant advertises, if any. */
function advertisedVariantRepresentation(variant) {
  if (typeof variant?.reasoningEffort === 'string' && variant.reasoningEffort.trim() !== '') {
    return { kind: 'reasoning-effort', value: variant.reasoningEffort };
  }
  if (isPlainObject(variant?.thinking)) {
    return { kind: 'anthropic-thinking', thinking: sortKeysDeep(variant.thinking) };
  }
  return null;
}

/**
 * Project executable effort profiles from the reviewed wire maps, using the
 * resolver's advertised variants only as disagreement evidence.
 *
 * The two inputs answer different questions and only the validated map is
 * authority. The snapshot says which reasoning variants OpenCode's own resolver
 * advertises; `PATCHES` says what clodex has actually exercised on the wire for
 * the route it runs. Every non-null reviewed map entry reaches the profile even
 * when the snapshot does not advertise it; snapshot agreement and disagreement
 * are recorded as cross-check evidence and can never widen or narrow the ladder.
 *
 * Both directions of disagreement are recorded rather than resolved:
 * a variant the map cannot execute (deepseek-v4-flash advertises `low`, the
 * reviewed map sends nothing for it), a variant whose representation the running
 * transport cannot carry (the Qwen and MiniMax Anthropic thinking objects), and
 * an executable level the snapshot does not advertise. Widening or narrowing on
 * any of them needs live validation, which is a review decision, not this
 * script's.
 */
export function buildEffortProfiles(snapshotModels, supported) {
  assertEffortMapsIdempotent();
  const bySnapshotId = new Map(snapshotModels.map(model => [model.id, model]));
  const errors = [];
  const profiles = [];
  const disagreements = [];

  for (const model of supported) {
    const transport = TRANSPORTS[model.id];
    const compatibility = model.compatibility ?? {};
    const map = compatibility.reasoningEffortMap;
    let levels;
    if (compatibility.supportsReasoningEffort === false) {
      // No clodex-operable effort control on this route at all. Distinct from an
      // unsupported LEVEL: there is no ladder to round along or reject against.
      levels = [];
    } else if (isPlainObject(map)) {
      levels = CANONICAL_EFFORT_LEVELS
        .filter(level => Object.hasOwn(map, level) && map[level] !== null)
        .map(level => ({ level, native: { kind: 'reasoning-effort', value: map[level] } }));
    } else {
      errors.push(
        `${model.id}: has neither a reviewed reasoningEffortMap nor an explicit `
        + 'supportsReasoningEffort: false, so no executable effort ladder can be stated',
      );
      continue;
    }

    const variants = bySnapshotId.get(model.id)?.variants ?? {};
    const levelByNative = new Map(levels.map(entry => [entry.native.value, entry.level]));
    const advertisedLevels = new Set();
    for (const variant of Object.keys(variants).sort(compareCodeUnits)) {
      const advertised = advertisedVariantRepresentation(variants[variant]);
      if (advertised === null) {
        disagreements.push({
          modelId: model.id,
          variant,
          advertised: null,
          reason: 'the resolver variant declares no reasoning representation this generator understands',
        });
        continue;
      }
      if (advertised.kind !== 'reasoning-effort') {
        disagreements.push({
          modelId: model.id,
          variant,
          advertised,
          reason: `the reviewed ${transport} route carries no clodex-controlled Anthropic thinking representation`,
        });
        continue;
      }
      const level = levelByNative.get(advertised.value);
      if (level === undefined) {
        disagreements.push({
          modelId: model.id,
          variant,
          advertised,
          reason: 'the reviewed wire map sends this value for no global effort level',
        });
        continue;
      }
      advertisedLevels.add(level);
    }

    const unadvertised = levels.map(entry => entry.level).filter(level => !advertisedLevels.has(level));
    if (unadvertised.length > 0) {
      disagreements.push({
        modelId: model.id,
        variant: null,
        advertised: null,
        reason: `the reviewed wire map executes ${unadvertised.join('/')}, which the resolver snapshot does not advertise`,
      });
    }

    profiles.push({
      modelId: model.id,
      transport,
      // The resolver declares variants as opt-in request overlays and names no
      // default among them, and `assertModelSchema` rejects any unknown model or
      // variant key — so a capture that grew a default marker would fail the
      // schema long before reaching here. Nothing else in this script is
      // entitled to invent one, so the explicit answer is "none declared".
      defaultLevel: null,
      levels,
    });
  }

  raiseEffortProfileErrors(errors);
  return { schemaVersion: 1, provider: PROVIDER_ID, profiles, disagreements };
}

async function loadSnapshot() {
  const snapshot = JSON.parse(await readFile(SNAPSHOT_PATH, 'utf8'));
  const errors = [];
  if (!isPlainObject(snapshot)) throw new Error('snapshot: expected a JSON object');
  assertKnownKeys('snapshot', snapshot, ['_meta', 'models'], errors);
  raise(errors);
  assertSnapshotMeta(snapshot._meta);
  assertResolvedModels(snapshot.models);
  const absent = Object.keys(TRANSPORTS).filter(id => !snapshot.models.some(model => model.id === id));
  if (absent.length > 0) {
    throw new Error(`Transport-mapped models are absent from the resolver snapshot: ${absent.join(', ')}`);
  }
  const digest = resolvedModelsSha256(snapshot.models);
  if (digest !== snapshot._meta.normalizedModelsSha256) {
    throw new Error(
      `Resolver snapshot rows do not match their recorded digest: computed ${digest}, `
      + `_meta.normalizedModelsSha256 says ${snapshot._meta.normalizedModelsSha256}`,
    );
  }
  return snapshot;
}

function constantPattern(name) {
  return new RegExp(`export const ${name} = '[^']*';`);
}

function readProvenanceConstants(source) {
  const found = {};
  for (const [name] of PROVENANCE_CONSTANTS) {
    const match = source.match(new RegExp(`export const ${name} = '([^']*)';`));
    if (match) found[name] = match[1];
  }
  return found;
}

/**
 * Resolve the new constants file content WITHOUT writing it.
 *
 * Ordering alone cannot make two file writes atomic — whichever goes first, an
 * interruption leaves the other stale. What it can do is move the one failure
 * that is actually likely, the regex ceasing to match after an unrelated edit
 * to the constants file, ahead of every write. Both writes then fail only on
 * real I/O trouble, and the catalog goes first so the provenance stamp marks a
 * catalog already on disk rather than a promise about one.
 */
async function prepareSourceConstants(meta) {
  const source = await readFile(CONSTANTS_PATH, 'utf8');
  if (!constantPattern(REQUIRED_CONSTANT).test(source)) {
    throw new Error(`Could not find ${REQUIRED_CONSTANT} in opencode-go-models.ts`);
  }
  let content = source;
  const absent = [];
  for (const [name, read] of PROVENANCE_CONSTANTS) {
    const pattern = constantPattern(name);
    if (!pattern.test(content)) {
      absent.push(`${name} = '${read(meta)}'`);
      continue;
    }
    content = content.replace(pattern, `export const ${name} = '${read(meta)}';`);
  }
  return { content, absent };
}

function deepEqual(a, b) {
  return JSON.stringify(sortKeysDeep(a)) === JSON.stringify(sortKeysDeep(b));
}

function serializeCatalog(supported) {
  return `${JSON.stringify(supported, null, 2)}\n`;
}

function serializeEffortProfiles(table) {
  return `${JSON.stringify(table, null, 2)}\n`;
}

/**
 * Offline verification that the committed generated files still say what the
 * committed snapshot says. Reads the snapshot plus all three generated files,
 * writes none, and never reaches the network — so it is safe to run anywhere
 * the repo is checked out.
 */
async function check(snapshot, supported, effortProfiles) {
  const failures = [];
  const committedText = await readFile(MODELS_PATH, 'utf8');
  const generatedText = serializeCatalog(supported);
  if (committedText !== generatedText) {
    let committed;
    try {
      committed = JSON.parse(committedText);
    } catch {
      committed = undefined;
    }
    const committedIds = Array.isArray(committed) ? committed.map(model => model?.id) : [];
    const generatedIds = supported.map(model => model.id);
    const drifted = Array.isArray(committed)
      ? generatedIds
        .filter(id => committedIds.includes(id))
        .filter(id => !deepEqual(committed.find(model => model?.id === id), supported.find(model => model.id === id)))
      : [];
    failures.push(
      `${MODELS_PATH} disagrees with the resolver snapshot`
      + `${drifted.length > 0 ? ` (models: ${drifted.join(', ')})` : ''}`
      + `${committedIds.length !== generatedIds.length ? ` (committed ${committedIds.length} ids, snapshot yields ${generatedIds.length})` : ''}`,
    );
  }

  const committedProfiles = await readFile(EFFORT_PROFILES_PATH, 'utf8');
  if (committedProfiles !== serializeEffortProfiles(effortProfiles)) {
    failures.push(`${EFFORT_PROFILES_PATH} disagrees with the resolver snapshot and the reviewed wire maps`);
  }

  const constants = readProvenanceConstants(await readFile(CONSTANTS_PATH, 'utf8'));
  for (const [name, read] of PROVENANCE_CONSTANTS) {
    const expected = read(snapshot._meta);
    if (!Object.hasOwn(constants, name)) failures.push(`${name} is missing from opencode-go-models.ts (expected '${expected}')`);
    else if (constants[name] !== expected) failures.push(`${name} is '${constants[name]}', snapshot says '${expected}'`);
  }

  if (failures.length > 0) {
    throw new Error(`OpenCode Go catalog is out of date with its committed resolver snapshot:\n  ${failures.join('\n  ')}`);
  }
}

/**
 * Run the advisory models.dev cross-check, and only then let the caller write.
 *
 * Everything here is a GATE on the snapshot-derived output, never an input to
 * it: no value models.dev returns reaches a generated file. Membership and
 * ladder disagreements throw, because the whole point of asking for this mode
 * is to be stopped by them before the files are replaced.
 */
async function verifyLadders(supported) {
  const catalog = await fetchJson(MODELS_DEV_URL);
  const devModels = catalog?.[PROVIDER_ID]?.models;
  if (!devModels || typeof devModels !== 'object') {
    throw new Error(`models.dev catalog has no "${PROVIDER_ID}" provider models`);
  }
  const missing = Object.keys(TRANSPORTS).filter(id => !Object.hasOwn(devModels, id));
  if (missing.length > 0) {
    throw new Error(`Transport-mapped models missing from models.dev: ${missing.join(', ')}`);
  }
  const ladders = assertEffortLadders(supported, devModels);
  if (ladders.errors.length > 0) {
    throw new Error(
      'Local effort maps send values models.dev does not publish for the OpenCode gateway:\n  '
      + ladders.errors.join('\n  '),
    );
  }
  return { notes: ladders.notes, unmapped: Object.keys(devModels).filter(id => !TRANSPORTS[id]) };
}

/**
 * Three modes, and only one of them has a network in it.
 *
 *   (no args)          regenerate the catalog and provenance from the committed
 *                      snapshot. Offline and deterministic: every written byte
 *                      derives from the snapshot, so the same commit always
 *                      reproduces the same files.
 *   --check            verify the committed files against the snapshot. Offline,
 *                      reads three files, writes none.
 *   --verify-ladders   the above regeneration, gated on the advisory models.dev
 *                      effort-ladder cross-check. Explicit, because it is the
 *                      one mode that can fail for a reason outside this repo.
 */
export async function run(argv = []) {
  // `pnpm update:opencode-go -- --check` forwards the separator itself, so a
  // leading bare `--` is dropped before parsing; without this the documented
  // invocation reaches parseArgs as a positional and is rejected.
  const args = argv[0] === '--' ? argv.slice(1) : argv;
  const { values } = parseArgs({
    args,
    options: {
      check: { type: 'boolean', default: false },
      'verify-ladders': { type: 'boolean', default: false },
    },
    strict: true,
    allowPositionals: false,
  });
  const verify = values['verify-ladders'];
  if (values.check && verify) {
    throw new Error('--check verifies the committed files offline and --verify-ladders regenerates them against models.dev; pick one');
  }

  const snapshot = await loadSnapshot();
  const { supported, unmapped, overrides, temperatureNotes, effortProfiles } = convertResolvedModels(snapshot.models);

  if (values.check) {
    await check(snapshot, supported, effortProfiles);
    console.log(
      `OpenCode Go catalog matches the committed resolver snapshot `
      + `(${supported.length} models, opencode ${snapshot._meta.openCodeVersion}).`,
    );
    return;
  }

  const advisory = verify ? await verifyLadders(supported) : { notes: [], unmapped: [] };

  // Resolve the constants content before either write, so the likely failure —
  // the regex no longer matching — aborts with both files untouched rather
  // than stranding one of them. Catalog first, provenance second: the stamp
  // then marks a catalog that is already on disk.
  const constants = await prepareSourceConstants(snapshot._meta);
  await writeFile(MODELS_PATH, serializeCatalog(supported));
  await writeFile(EFFORT_PROFILES_PATH, serializeEffortProfiles(effortProfiles));
  await writeFile(CONSTANTS_PATH, constants.content);

  console.log(
    `Updated ${supported.length} OpenCode Go models from the committed resolver snapshot `
    + `(opencode ${snapshot._meta.openCodeVersion}, captured ${snapshot._meta.capturedAt}).`,
  );
  for (const override of overrides) {
    console.log(`Reviewed transport override — ${override}`);
  }
  for (const note of temperatureNotes) {
    console.log(`Temperature capability note — ${note}`);
  }
  for (const disagreement of effortProfiles.disagreements) {
    const where = disagreement.variant === null
      ? disagreement.modelId
      : `${disagreement.modelId} variant ${disagreement.variant}`;
    console.log(`Effort profile disagreement — ${where}: ${disagreement.reason}`);
  }
  for (const note of advisory.notes) {
    console.log(`Effort ladder note — ${note}`);
  }
  if (!verify) {
    console.log('Effort ladders not cross-checked — rerun with --verify-ladders to compare them against models.dev.');
  }
  for (const name of constants.absent) {
    console.log(`Provenance constant absent from opencode-go-models.ts — add export const ${name};`);
  }
  const unknown = [...new Set([...unmapped, ...advisory.unmapped])].sort(compareCodeUnits);
  if (unknown.length > 0) {
    console.log(
      `Present in the resolver snapshot${verify ? ' or on models.dev' : ''} but not transport-mapped `
      + `(verify wire protocol against the live endpoint, then add to TRANSPORTS): ${unknown.join(', ')}`,
    );
  }
}

// Run when invoked as a program — directly, or through a bootstrap that has no
// script path of its own (`node -e`). Importing this module into a host with
// its own entry point, such as the test runner, exposes the functions above
// without executing anything.
const entryPoint = process.argv[1];
if (entryPoint === undefined || pathToFileURL(entryPoint).href === import.meta.url) {
  run(process.argv.slice(2)).catch(error => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
